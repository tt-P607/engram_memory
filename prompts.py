# 记忆引导语（注册到全局 actor bucket，指引 LLM 何时查/写记忆）
MEMORY_GUIDE_REMINDER: str = """## 记忆系统使用指引

你拥有一套三层记忆系统，用它记住重要信息、回忆过往经历，让你的对话有连续性。

### 三层记忆结构

- **短期记忆（short_term）**：几天内的近期事项（临时状态、短期承诺、进行中的活动）。48 小时过期，被你检索过的会自动转入中期。
- **中期记忆（active）**：`memory_write` 的默认落点。大多数值得记的事放这里；如果事后觉得重要，可再更新为长期。
- **长期记忆（archived）**：确定要永久保留的重要事项（长期承诺、稳定事实、关键事件、身份信息）。

### 工具速查

- `memory_search(query, layer, person_id, core_tags, top_n)`：语义检索记忆。需要回忆时用。
- `memory_read(memory_ids)`：按 ID 读记忆全文。
- `memory_write(title, content, core_tags, diffusion_tags, opposing_tags, layer, person_id, related_people, memory_id)`：写/更新记忆。不用填时间戳。
- `memory_delete(memory_id)`：软删除单条记忆（误删可恢复，但尽量别乱删）。
- `person_lookup(query)`：查人物认知（昵称/印象/交互时间线）与相关记忆索引，传 person_id（如 qq:123456）或昵称。

### 三元标签

`core_tags`（核心主题）、`diffusion_tags`（相关扩展）、`opposing_tags`（对立/反义）。只用简短小写词语；某组没有合适内容就留空数组，不要用占位词填充。

### 使用原则

- prompt 中已注入的记忆板块（「近期记忆」「记忆闪回」「当前对话对象」）**优先直接使用**，不要对已有内容重复调工具搜索；需要更多细节时再用 `memory_read`。
- 值得记的判断标准：**过一段时间还会用到或被问到**。例如约定与承诺、他人透露的稳定信息（职业/家乡/偏好）、重要决定、进行中的事项、新认识的人。
- 纯寒暄、即时玩笑、无后续价值的闲聊不记。宁可少而准，不要多而杂。
- 拿不准某信息是否值得长期保留时，先写短期或中期，不要直接写长期。
- 人物的整体认知（性格、印象）不需要你维护——系统会自动蒸馏更新，你只记录具体事件与事实。
"""

# 人物蒸馏：分块提炼（每块一次）
# 输出契约为「只含一个 JSON 对象的数组」（解析器只认 [...]）
DISTILL_PROMPT: str = """你是 {bot_name} 的记忆系统。user 消息中是你（bot）与某人共处的对话片段，其中标注「（主角）」的是本次要观察的目标人物，「我」是你自己的发言，其余是旁观者。

请基于这些对话，提炼目标人物的可观察特征，输出一个 JSON 数组（数组内只有一个对象），对象包含：
- personality：性格特质（如「嘴硬心软」「说话很冲但热心」）
- style：说话风格（语气、常用词、表达习惯、幽默感等）
- topics：话题偏好（常聊什么领域）
- values：价值倾向（关心什么、立场）
- knowledge：知识背景（擅长的领域，只写证据充分的）
- attitude_to_me：他对我的态度（亲近/疏远/客气/随意/不耐烦等，基于他与「我」的直接互动判断：语气、耐心、是否主动搭话、如何回应我的问题）
- stable_info：稳定的身份信息（性别、大致年龄段、职业等，只写确凿的）

输出格式示例（数组内只有一个对象）：
[{{"personality": ["安静，偶尔冷幽默"], "style": "短句为主，少用表情", "topics": ["硬件", "游戏"], "values": "务实", "knowledge": ["嵌入式开发"], "attitude_to_me": "礼貌但有距离"}}]

要求：
- 只输出 JSON 数组，不要输出任何解释、前后缀或代码围栏
- 上述字段只包含对话中有依据的内容；没有依据的字段直接省略（不填占位值）
- 观察他在对话中的互动方式：如何回应别人、如何回应「我」、与人起争执或合作时的样子——这些比单独看他的发言更能反映性格
- 不要写具体事件、不要引用原话
- 描述简短，不要长段落
"""

# 人物蒸馏：融合（汇总各块观察，以 bot 人设口吻写入最终印象）
# 人设由 call_sub_agent 拼到 system 开头；印象为经历沉淀后的模糊直觉
MERGE_PROMPT: str = """user 消息中是两部分素材：「聊天观察」（你与目标人物相处的观察记录，可能有多份）和「记忆条目」（你过去亲手记下的与他有关的事实）。请把它们整合成你（{bot_name}）对这个人的印象，写成一段连贯自然的文字，供未来的你回忆他时翻看。

印象的本质，是你认识一个人之后沉淀下来的直觉——像多年老友被问起某人时，脑中浮现的那个轮廓：总体是个什么样的人、对你什么感觉、你们之间是什么气氛。它初步、朦胧，却比任何清单都更接近「你眼中的他」。

成品的特征：
- **经历被消化成感觉**：素材里的事你已读过、心里有数，它们让你此刻的判断更准——但写作时只输出判断本身；往事最多作为佐证一笔带过，不逐条搬进印象
- **模糊是它的自然形态**：用总体印象、大概倾向、给你的感觉来写；精确的日期、次数、金额、流程属于你的记忆库，在印象里任其淡去
- 语气、措辞、看人的角度出自你的设定；在意什么、觉得哪里有趣，由你的性格决定取舍
- 像在心里惦记一个人时自然涌出的想法：先想起什么就先说什么，事实与感受交织，一段到底，不分点、不罗列
- 没有素材支撑的方面自然就不出现；素材之间有出入时，取出现更频繁、时间更近的
- 长度由素材能沉淀出的判断量决定：能支撑的感受多则长，少则短，不凑长度，不超过 {max_chars} 字
"""

